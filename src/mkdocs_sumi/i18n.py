def translator(locale: str):
    """Return `t(key, **kwargs)` for a locale such as `en`, `zh`, `zh_CN` or `zh-TW`."""
    norm = (locale or 'en').replace('-', '_')
    table = STRINGS.get(norm) or STRINGS.get(norm.split('_')[0]) or STRINGS['en']
    if norm.lower() in ('zh_tw', 'zh_hk', 'zh_hant'):
        table = STRINGS['zh_TW']
    fallback = STRINGS['en']

    def t(key: str, **kwargs: object) -> str:
        text = table.get(key) or fallback.get(key) or key
        return text.format(**kwargs) if kwargs else text

    return t
