def normalize(locale: str | None) -> str:
    """`zh-CN` -> `zh`, `pt-br` -> `pt_BR`: the key of the closest table in STRINGS."""
    norm = (locale or 'en').replace('-', '_')
    lower = norm.lower()
    if lower in ('zh_tw', 'zh_hk', 'zh_hant', 'zh_mo'):
        return 'zh_TW'
    for key in STRINGS:
        if key.lower() == lower:
            return key
    base = lower.split('_')[0]
    return base if base in STRINGS else 'en'


def is_rtl(locale: str | None) -> bool:
    return (locale or '').replace('-', '_').split('_')[0].lower() in RTL


def og_locale(locale: str | None) -> str:
    norm = normalize(locale)
    return OG_LOCALES.get(norm) or (locale or 'en').replace('-', '_')


def format_date(year: int, month: int, day: int, locale: str = 'en', short: bool = False) -> str:
    """A long date in the page's language: "November 5, 2026", "5. November 2026", "2026年11月5日"."""
    lang = (locale or 'en').replace('-', '_').split('_')[0].lower()
    if lang in ('zh', 'ja'):
        return f'{year}年{month}月{day}日'
    if lang == 'ko':
        return f'{year}년 {month}월 {day}일'
    if lang in _DATE_FORMATS:
        name = _MONTHS[lang].split()[month - 1]
        return _DATE_FORMATS[lang].format(d=day, month=name, y=year)
    name = _MONTHS['en'].split()[month - 1]
    return f'{name[:3] if short else name} {day}, {year}'


def translator(locale: str):
    """Return `t(key, **kwargs)` for a locale such as `en`, `zh`, `zh_CN`, `zh-TW` or `pt-BR`."""
    table = STRINGS[normalize(locale)]
    fallback = STRINGS['en']

    def t(key: str, **kwargs: object) -> str:
        text = table.get(key) or fallback.get(key) or key
        return text.format(**kwargs) if kwargs else text

    return t
